/** Переклад поширених текстів помилок бекенда при подачі результату кваліфікації. */
export function friendlyQualificationSubmitError (msg: string): string {
  const hints: Record<string, string> = {
    'Тільки капітан однієї з команд може подати матч':
      'Лише капітани однієї з цих команд можуть надсилати ID матчу.',
    'Результат цього матчу вже подано': 'Результат для цього призначення вже збережено.',
    'У лобі матчі було не 10 гравців': 'У лобі повинні бути 10 гравців.',
    'Матч тривав менше 15 хвилин': 'Матч тривав занадто коротко (менше 15 хв).',
    'Матч завершився після закінчення кваліфікаційного етапу':
      'Матч був зіграний пізніше дозволеного вікна кваліфікації.',
    'ID команд у матчі не збігаються з очікуваними':
      'Склад у лобі не відповідає затвердженому матчу.',
    'Не вдалося отримати дані матчу з OpenDota':
      'Не вдалося отримати матч із OpenDota. Спробуйте ще раз.'
  }
  const direct = hints[msg.trim()]
  if (direct) return direct
  if (msg.includes('Гравець зі Steam ID') && msg.includes('не знайдений')) {
    return 'Розходження між матчем і заявленим складом.'
  }
  return msg.trim() || 'Сталася помилка'
}
